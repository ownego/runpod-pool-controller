"""The nginx proxy's slots: which RunPod pod sits behind which local port.

The slots live in their own ConfigMap (spec.nginx.slotsConfigMap), owned by
the controller, which the static proxy config pulls in with `include`:

    upstream.conf     server lines for the load-balancing upstream block
    slots.conf        one server block per slot, proxying to one RunPod pod
    metrics-pin.conf  routes the proxy's own /metrics to one slot

Keeping them out of the static config means applying that config from git
never resets the slots to whatever pods were current when it was written.
RunPod's proxy routes on the Host header ({pod}-{port}.proxy.runpod.net), so
each pod needs its own server block; one upstream cannot carry several Hosts.
"""

import re

_SLOT = re.compile(
    r"listen\s+(\d+);\s*\n\s*set\s+\$upstream_host\s+([a-z0-9]+)-\d+\.proxy\.runpod\.net;"
)

UPSTREAM_KEY = "upstream.conf"
SLOTS_KEY = "slots.conf"
METRICS_PIN_KEY = "metrics-pin.conf"
# Marks the deliberately empty render, so "no slots" can be told apart from
# a ConfigMap the parser does not understand.
EMPTY_MARKER = "# no Ready members"


def parse_slots(conf):
    """Return {listen_port: pod_id} for every slot server block in conf."""
    return {int(port): pod for port, pod in _SLOT.findall(conf)}


def slot_letter(port, base_port):
    """8081 -> "a", 8082 -> "b", ... matching the existing `slot` label."""
    index = port - base_port
    if not 0 <= index < 26:
        raise ValueError(f"port {port} is outside the slot range starting at {base_port}")
    return chr(ord("a") + index)


def assign_ports(current, wanted, base_port, max_slots):
    """Give each wanted pod a port, keeping pods that are already wired on theirs.

    current: {port: pod_id} as wired now. wanted: pod ids to be wired.
    Stable ports keep the `slot` label and nginx state of untouched pods.
    """
    wanted = list(dict.fromkeys(wanted))
    keep = {port: pod for port, pod in current.items() if pod in wanted}
    free = [p for p in range(base_port, base_port + max_slots) if p not in keep]
    placed = set(keep.values())
    for pod in wanted:
        if pod in placed:
            continue
        if not free:
            raise ValueError(f"more pods to wire than the {max_slots} slot ports")
        keep[free.pop(0)] = pod
        placed.add(pod)
    return dict(sorted(keep.items()))


_SLOT_BLOCK = """\
# Slot {letter} -- RunPod pod {pod}{note}
server {{
  listen {port};
  set $upstream_host {pod}-{pod_port}.proxy.runpod.net;

  location / {{
    client_max_body_size 50m;
    resolver 8.8.8.8 ipv6=off;

    proxy_pass https://$upstream_host;
    proxy_set_header Host $upstream_host;
    proxy_ssl_server_name on;
    proxy_ssl_name $upstream_host;

    proxy_read_timeout {read_timeout};
  }}
}}
"""

_HEADER = "# Generated by runpod-pool-controller for pool {pool}. Do not edit:\n# changes are overwritten on the next reconcile.\n"


def render(pool, slots, base_port, notes=None, read_timeout="120s", fail_timeout="30s", max_fails=3,
           pod_port=80):
    """Render the slots ConfigMap data for {port: pod_id}.

    An empty pool renders a `down` placeholder server so the upstream block
    stays valid for nginx; requests then fail fast with 502 instead of nginx
    refusing to start.
    """
    notes = notes or {}
    header = _HEADER.format(pool=pool)
    if slots:
        upstream = "".join(
            f"server 127.0.0.1:{port} max_fails={max_fails} fail_timeout={fail_timeout};\n"
            for port in sorted(slots)
        )
        blocks = "\n".join(
            _SLOT_BLOCK.format(
                letter=slot_letter(port, base_port).upper(), pod=pod, port=port,
                note=f" ({notes[pod]})" if notes.get(pod) else "", read_timeout=read_timeout,
                pod_port=pod_port,
            )
            for port, pod in sorted(slots.items())
        )
        pin = f"location = /metrics {{\n  proxy_pass http://127.0.0.1:{min(slots)};\n}}\n"
    else:
        upstream = f"server 127.0.0.1:{base_port} down;\n"
        blocks = EMPTY_MARKER + "\n"
        pin = "location = /metrics {\n  return 503;\n}\n"
    return {
        UPSTREAM_KEY: header + upstream,
        SLOTS_KEY: header + blocks,
        METRICS_PIN_KEY: header + pin,
    }
